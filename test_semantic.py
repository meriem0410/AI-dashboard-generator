# MAIN
# ============================================================

def main():

    total_start = time.perf_counter()

    # ========================================================
    # 1. LOAD DATA
    # ========================================================

    print("\n🚀 Loading data...")

    dataset = data_agent(
        "data/Logistics"
    )

    data = dataset["data"]

    # ========================================================
    # 2. PROFILE DATA
    # ========================================================
    #
    # IMPORTANT:
    # We do this ONCE for all five tests.
    #
    # ========================================================

    print("\n📊 Profiling data...\n")

    profile_start = time.perf_counter()

    profile = profile_data(
        data
    )

    profile_time = (
        time.perf_counter()
        - profile_start
    )

    print(
        f"\n⏱️ Profiling completed in "
        f"{profile_time:.3f}s"
    )

    # Optional: preserve the same output as your normal pipeline

    with open(
        "profile_output.json",
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            profile,
            f,
            indent=4,
            default=str
        )

    # ========================================================
    # 3. BUILD SCHEMA
    # ========================================================

    print("\n🧠 Building LLM schema...\n")

    schema = build_llm_schema(
        profile
    )

    save_schema(
        schema
    )

    print("✅ Schema ready.")

    # ========================================================
    # 4. RUN ALL SEMANTIC TESTS
    # ========================================================

    print("\n")
    print("#" * 80)
    print("#                 SEMANTIC TEST SUITE")
    print("#" * 80)

    print(
        f"\nRunning {len(SEMANTIC_TESTS)} difficult queries..."
    )

    results = {}

    for test_id, test in SEMANTIC_TESTS.items():

        print("\n")
        print("=" * 80)
        print(
            f"▶ Running {test_id} "
            f"({list(SEMANTIC_TESTS).index(test_id) + 1}/"
            f"{len(SEMANTIC_TESTS)})"
        )
        print("=" * 80)

        start = time.perf_counter()

        try:

            result = sql_agent(
                test["question"],
                schema
            )

        except Exception as e:

            result = {
                "success": False,
                "error": str(e),
                "stage": "generation",
                "generation_time": 0,
                "validation_time": 0,
                "execution_time": 0
            }

        elapsed = (
            time.perf_counter()
            - start
        )

        result["total_test_time"] = elapsed

        results[test_id] = result

        display_test_result(
            test_id,
            test,
            result
        )

    # ========================================================
    # 5. FINAL TEST SUMMARY
    # ========================================================

    print("\n")
    print("#" * 80)
    print("#                       SUMMARY")
    print("#" * 80)

    print(
        "\nID     Generation     Schema       Execution"
    )

    print("-" * 60)

    for test_id, result in results.items():

        generation = (
            "PASS"
            if result.get("success")
            or result.get("raw_response")
            else "FAIL"
        )

        validation = result.get(
            "validation"
        )

        if validation is None:

            schema_status = "N/A"

        elif validation.get(
            "schema_valid",
            False
        ):

            schema_status = "PASS"

        else:

            schema_status = "FAIL"

        if result.get("stage") == "completed":

            execution = "PASS"

        elif result.get("stage") == "execution":

            execution = "FAIL"

        else:

            execution = "N/A"

        print(
            f"{test_id:<6}"
            f"{generation:<15}"
            f"{schema_status:<13}"
            f"{execution}"
        )

    # ========================================================
    # 6. SAVE RESULTS
    # ========================================================
    #
    # This lets you come back later and inspect exactly what
    # happened without rerunning the LLM.
    #
    # ========================================================

    output = {}

    for test_id, result in results.items():

        output[test_id] = {

            "question": SEMANTIC_TESTS[
                test_id
            ]["question"],

            "focus": SEMANTIC_TESTS[
                test_id
            ]["focus"],

            "success": result.get(
                "success"
            ),

            "stage": result.get(
                "stage"
            ),

            "error": result.get(
                "error"
            ),

            "generation_time": result.get(
                "generation_time"
            ),

            "validation_time": result.get(
                "validation_time"
            ),

            "execution_time": result.get(
                "execution_time"
            ),

            "sql": result.get(
                "sql"
            ),

            "raw_response": result.get(
                "raw_response"
            ),

            "validation": result.get(
                "validation"
            ),

            "rows_returned": (
                len(result["result"])
                if result.get("result") is not None
                else None
            )
        }

    with open(
        "semantic_test_results.json",
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            output,
            f,
            indent=4,
            default=str
        )

    # ========================================================
    # 7. TOTAL TIME
    # ========================================================

    total_time = (
        time.perf_counter()
        - total_start
    )

    print("\n")
    print("#" * 80)
    print(
        f"✅ Test suite completed in "
        f"{total_time:.3f}s"
    )
    print(
        "📁 Results saved to: semantic_test_results.json"
    )
    print("#" * 80)


# ============================================================
# RUN
# ============================================================

if __name__ == "__main__":
    main()
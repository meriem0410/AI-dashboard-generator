# ============================================================
# DISPLAY ONE TEST RESULT
# ============================================================

def display_test_result(test_id, test, result):

    print("\n")
    print("=" * 80)
    print(f"                         {test_id}")
    print("=" * 80)

    print("\n🎯 WHAT THIS TESTS")
    print(f"   {test['focus']}")

    print("\n❓ QUESTION")
    print(f"   {test['question']}")

    # --------------------------------------------------------
    # GENERATION
    # --------------------------------------------------------

    print("\n🤖 SQL GENERATION")

    if result.get("success"):

        print("   Status : ✅ SUCCESS")
        print(
            f"   Time   : "
            f"{result.get('generation_time', 0):.3f}s"
        )

    else:

        print("   Status : ❌ FAILED")
        print(f"   Error  : {result.get('error')}")

        if result.get("generation_time") is not None:
            print(
                f"   Time   : "
                f"{result.get('generation_time', 0):.3f}s"
            )

    # --------------------------------------------------------
    # RAW RESPONSE
    # --------------------------------------------------------

    if result.get("raw_response"):

        print("\n🔍 RAW LLM RESPONSE")
        print("-" * 80)
        print(result["raw_response"])
        print("-" * 80)

    # --------------------------------------------------------
    # EXTRACTED SQL
    # --------------------------------------------------------

    if result.get("sql"):

        print("\n📝 EXTRACTED SQL")
        print("-" * 80)
        print(result["sql"])
        print("-" * 80)

    # --------------------------------------------------------
    # SCHEMA VALIDATION
    # --------------------------------------------------------

    validation = result.get("validation")

    print("\n📐 SCHEMA VALIDATION")

    if validation is None:

        print("   Status : ⏭️ NOT REACHED")

    elif validation.get("schema_valid", False):

        print("   Status : ✅ PASS")

    else:

        print("   Status : ❌ FAIL")

        for error in validation.get(
            "schema_errors",
            []
        ):
            print(f"      • {error}")

    print(
        f"   Time   : "
        f"{result.get('validation_time', 0):.3f}s"
    )

    # --------------------------------------------------------
    # EXECUTION
    # --------------------------------------------------------

    print("\n⚙️ SQL EXECUTION")

    if result.get("stage") == "completed":

        print("   Status : ✅ PASS")

        df = result.get("result")

        if df is not None:
            print(f"   Rows   : {len(df)}")

    elif result.get("stage") == "execution":

        print("   Status : ❌ FAIL")
        print(f"   Error  : {result.get('error')}")

    else:

        print("   Status : ⏭️ NOT REACHED")

    print(
        f"   Time   : "
        f"{result.get('execution_time', 0):.3f}s"
    )

    # --------------------------------------------------------
    # SQL STRUCTURE
    # --------------------------------------------------------

    if result.get("sql"):

        try:

            analysis = analyze_sql(
                result["sql"]
            )

            print("\n🧠 SQL STRUCTURE")
            print("-" * 80)

            print(
                json.dumps(
                    analysis,
                    indent=4
                )
            )

        except Exception as e:

            print("\n⚠️ SQL STRUCTURE ANALYSIS FAILED")
            print(f"   {e}")

    # --------------------------------------------------------
    # RESULT PREVIEW
    # --------------------------------------------------------

    if result.get("success"):

        df = result.get("result")

        if df is not None:

            print("\n📊 RESULT PREVIEW")
            print("-" * 80)

            print(
                df.head(10).to_string(
                    index=False
                )
            )

            print(
                f"\n   Rows returned: {len(df)}"
            )

    # --------------------------------------------------------
    # IMPORTANT: NO SEMANTIC JUDGMENT YET
    # --------------------------------------------------------

    print("\n🧠 SEMANTIC VALIDATION")
    print("-" * 80)

    print("   Status : 🔎 MANUAL REVIEW REQUIRED")

    print(
        "   This test currently checks execution only."
    )

    print(
        "   Review the generated SQL manually for:"
    )

    print(
        "      • intent / business meaning"
    )

    print(
        "      • joins and relationship path"
    )

    print(
        "      • aggregation grain"
    )

    print(
        "      • duplicate measures"
    )

    print(
        "      • filters and date interpretation"
    )

    print(
        "      • ranking / HAVING logic"
    )

    print(
        "      • UNKNOWN records"
    )

    print("=" * 80)


